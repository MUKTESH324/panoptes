"""Renderers for a HuntResult (plan + validation + chains + diff)."""

from __future__ import annotations

import json

from ..models import Severity

_EMOJI = {
    Severity.CRITICAL: "🟥",
    Severity.HIGH: "🟧",
    Severity.MEDIUM: "🟨",
    Severity.LOW: "🟦",
    Severity.INFO: "⬜",
}


def render_hunt_json(hunt) -> str:
    return json.dumps(hunt.to_dict(), indent=2)


def render_hunt_markdown(hunt) -> str:
    v = hunt.validation
    lines = [
        f"# Panoptes hunt report — {hunt.target}",
        "",
        f"- **Duration:** {hunt.duration:.1f}s",
        f"- **URLs scanned:** {hunt.urls_scanned}",
        f"- **AI provider:** {hunt.meta.get('ai_provider', 'null')}",
    ]
    if hunt.signals:
        tech = ", ".join(hunt.signals.get("tech") or []) or "unknown"
        lines += [
            f"- **Tech observed:** {tech}",
            f"- **WAF:** {hunt.signals.get('waf') or 'none detected'}",
        ]

    # Plan
    lines += ["", "## Attack plan", ""]
    if hunt.plan:
        for ph in hunt.plan.phases:
            lines.append(f"- **{ph.name}**: {', '.join(ph.plugins)} — {ph.rationale}")
        for note in hunt.plan.notes:
            lines.append(f"  - _{note}_")

    # Validation summary
    if v:
        s = v.summary()
        lines += [
            "",
            "## Validation",
            "",
            f"- ✅ confirmed: {s['confirmed']}",
            f"- 🔎 needs review: {s['needs_review']}",
            f"- 🗑️ likely false positive: {s['likely_fp']} (dropped from findings)",
        ]

    # Exploit chains
    lines += ["", "## Exploit chains", ""]
    if hunt.chains:
        for c in hunt.chains:
            sev = Severity.from_name(c.severity.name)
            lines += [
                f"### {_EMOJI[sev]} {c.name} ({c.severity.name.title()})",
                "",
                c.narrative,
                "",
                f"_Components: {', '.join(c.components)}_",
                "",
            ]
    else:
        lines.append("_No multi-step chains inferred._")

    # Diff
    if hunt.diff:
        d = hunt.diff
        lines += [
            "",
            "## Changes since last run",
            "",
            f"- 🆕 new: {len(d.new)}",
            f"- ♻️ known: {len(d.known)}",
            f"- ✅ resolved: {len(d.resolved)}",
        ]
        for f in d.new:
            lines.append(f"  - NEW: {f.title} (`{f.url}`)")
        for r in d.resolved:
            lines.append(f"  - RESOLVED: {r['title']} (`{r['url']}`)")

    # Findings
    lines += ["", "## Findings (confirmed + needs-review)", ""]
    findings = hunt.findings
    if not findings:
        lines.append("_No findings kept after validation._")
    for i, f in enumerate(findings, 1):
        lines += [
            f"### {i}. {_EMOJI[f.severity]} {f.title}",
            "",
            f"- **Severity:** {f.severity.name.title()}  |  **URL:** `{f.url}`  |  "
            f"**Plugin:** `{f.plugin}`" + (f"  |  **{f.cwe}**" if f.cwe else ""),
            "",
            f.description,
            "",
        ]
        if f.evidence:
            lines += ["```", f.evidence, "```", ""]
        if f.remediation:
            lines += [f"**Fix:** {f.remediation}", ""]

    if hunt.errors:
        lines += ["## Errors", ""] + [f"- {e}" for e in hunt.errors]

    lines += ["", "---", "", "_Generated by Panoptes hunt — authorized security testing only._"]
    return "\n".join(lines)


def render_hunt(hunt, fmt: str) -> str:
    fmt = fmt.lower()
    if fmt == "json":
        return render_hunt_json(hunt)
    if fmt in ("markdown", "md"):
        return render_hunt_markdown(hunt)
    raise ValueError(f"hunt supports json|markdown, not {fmt!r}")

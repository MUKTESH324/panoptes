"""Markdown report — HackerOne-friendly, one section per finding."""

from __future__ import annotations

import datetime as _dt

from ..models import ScanResult, Severity

_EMOJI = {
    Severity.CRITICAL: "🟥",
    Severity.HIGH: "🟧",
    Severity.MEDIUM: "🟨",
    Severity.LOW: "🟦",
    Severity.INFO: "⬜",
}


def render_markdown(result: ScanResult) -> str:
    counts = result.counts_by_severity()
    when = _dt.datetime.utcfromtimestamp(result.started_at).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        f"# Panoptes scan report — {result.target}",
        "",
        f"- **Scanned:** {when}",
        f"- **Duration:** {result.duration:.1f}s",
        f"- **URLs scanned:** {result.urls_scanned}",
        f"- **Findings:** {len(result.findings)}",
        "",
        "## Summary",
        "",
        "| Severity | Count |",
        "| --- | --- |",
    ]
    for sev in sorted(Severity, reverse=True):
        lines.append(f"| {_EMOJI[sev]} {sev.name.title()} | {counts[str(sev)]} |")
    lines += ["", "## Findings", ""]

    if not result.findings:
        lines.append("_No findings._")
    for i, f in enumerate(result.findings, 1):
        lines += [
            f"### {i}. {_EMOJI[f.severity]} {f.title}",
            "",
            f"- **Severity:** {f.severity.name.title()}",
            f"- **Confidence:** {str(f.confidence).title()}",
            f"- **URL:** `{f.url}`"
            + (f"  _(and {f.occurrences - 1} more location(s))_" if f.occurrences > 1 else ""),
            f"- **Plugin:** `{f.plugin}`",
        ]
        if f.cwe:
            lines.append(f"- **CWE:** {f.cwe}")
        if f.owasp:
            lines.append(f"- **OWASP:** {f.owasp}")
        lines += ["", f.description, ""]
        if f.evidence:
            lines += ["**Evidence**", "", "```", f.evidence, "```", ""]
        if f.remediation:
            lines += ["**Remediation**", "", f.remediation, ""]
        if f.references:
            lines += ["**References**", ""] + [f"- {r}" for r in f.references] + [""]

    if result.errors:
        lines += ["## Scan errors", ""] + [f"- {e}" for e in result.errors]

    lines += ["", "---", "", "_Generated by Panoptes — authorized security testing only._"]
    return "\n".join(lines)

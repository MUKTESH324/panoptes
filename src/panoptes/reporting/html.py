"""Self-contained HTML report (no external assets, light/dark aware)."""

from __future__ import annotations

import datetime as _dt
import html

from ..models import ScanResult, Severity

_COLOR = {
    Severity.CRITICAL: "#b91c1c",
    Severity.HIGH: "#ea580c",
    Severity.MEDIUM: "#ca8a04",
    Severity.LOW: "#2563eb",
    Severity.INFO: "#64748b",
}


def render_html(result: ScanResult) -> str:
    e = html.escape
    counts = result.counts_by_severity()
    when = _dt.datetime.utcfromtimestamp(result.started_at).strftime("%Y-%m-%d %H:%M UTC")

    chips = "".join(
        f'<span class="chip" style="--c:{_COLOR[s]}">{s.name.title()}: '
        f'{counts[str(s)]}</span>'
        for s in sorted(Severity, reverse=True)
    )

    cards = []
    for i, f in enumerate(result.findings, 1):
        refs = "".join(f"<li><a href=\"{e(r)}\">{e(r)}</a></li>" for r in f.references)
        cards.append(
            f"""
      <article class="finding" style="--c:{_COLOR[f.severity]}">
        <header>
          <span class="sev">{f.severity.name.title()}</span>
          <h3>{i}. {e(f.title)}</h3>
        </header>
        <dl>
          <dt>URL</dt><dd><code>{e(f.url)}</code></dd>
          <dt>Plugin</dt><dd><code>{e(f.plugin)}</code></dd>
          <dt>Confidence</dt><dd>{e(str(f.confidence).title())}</dd>
          {f'<dt>CWE</dt><dd>{e(f.cwe)}</dd>' if f.cwe else ''}
          {f'<dt>OWASP</dt><dd>{e(f.owasp)}</dd>' if f.owasp else ''}
        </dl>
        <p>{e(f.description)}</p>
        {f'<h4>Evidence</h4><pre>{e(f.evidence)}</pre>' if f.evidence else ''}
        {f'<h4>Remediation</h4><p>{e(f.remediation)}</p>' if f.remediation else ''}
        {f'<h4>References</h4><ul>{refs}</ul>' if refs else ''}
      </article>"""
        )

    body_cards = "\n".join(cards) or "<p>No findings.</p>"
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Panoptes report — {e(result.target)}</title>
<style>
  :root {{ color-scheme: light dark; --bg:#fff; --fg:#111827; --muted:#6b7280; --card:#f9fafb; --border:#e5e7eb; }}
  @media (prefers-color-scheme: dark) {{ :root {{ --bg:#0b0f17; --fg:#e5e7eb; --muted:#9ca3af; --card:#111827; --border:#1f2937; }} }}
  * {{ box-sizing: border-box; }}
  body {{ margin:0; padding:2rem 1rem; font:15px/1.6 system-ui,sans-serif; background:var(--bg); color:var(--fg); }}
  .wrap {{ max-width: 920px; margin: 0 auto; }}
  h1 {{ font-size: 1.6rem; margin:0 0 .25rem; }}
  .meta {{ color:var(--muted); margin-bottom:1.25rem; }}
  .chips {{ display:flex; flex-wrap:wrap; gap:.5rem; margin-bottom:1.5rem; }}
  .chip {{ padding:.25rem .6rem; border-radius:999px; font-size:.8rem; font-weight:600;
           color:#fff; background:var(--c); }}
  .finding {{ border:1px solid var(--border); border-left:5px solid var(--c);
              background:var(--card); border-radius:10px; padding:1rem 1.25rem; margin:1rem 0; }}
  .finding header {{ display:flex; align-items:center; gap:.75rem; }}
  .finding h3 {{ margin:0; font-size:1.05rem; }}
  .sev {{ background:var(--c); color:#fff; font-size:.7rem; font-weight:700;
          padding:.15rem .5rem; border-radius:6px; text-transform:uppercase; }}
  dl {{ display:grid; grid-template-columns:auto 1fr; gap:.1rem .75rem; margin:.75rem 0; }}
  dt {{ color:var(--muted); font-weight:600; }}
  dd {{ margin:0; }}
  pre {{ background:rgba(127,127,127,.12); padding:.75rem; border-radius:8px; overflow:auto; }}
  code {{ font-family: ui-monospace, monospace; }}
  footer {{ color:var(--muted); font-size:.8rem; margin-top:2rem; }}
</style>
</head>
<body>
  <div class="wrap">
    <h1>Panoptes scan report</h1>
    <div class="meta">
      Target <code>{e(result.target)}</code> · {when} ·
      {result.urls_scanned} URLs · {result.duration:.1f}s ·
      {len(result.findings)} findings
    </div>
    <div class="chips">{chips}</div>
    {body_cards}
    <footer>Generated by Panoptes — authorized security testing only.</footer>
  </div>
</body>
</html>"""
